/**
 * Inline the three authored modules into DSH's lazy-CJS browser factory.
 * Only this project's imports are supported; unexpected syntax fails the build.
 * Usage: node client/build.mjs [--check]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { Script } from "node:vm";
import * as model from "./model.js";

const root = new URL("../", import.meta.url);
const read = (file) => readFileSync(new URL(file, root), "utf8");
const imports = new Map([
	['import React from "react";', 'const React = require("react");'],
	['import * as model from "./model.js";', ""],
	['import { createUi } from "./ui.js";', ""],
]);

function inline(file) {
	return read(file).split("\n").map((line, index) => {
		const text = line.trim();
		if (/^import\b/.test(text)) {
			if (file !== "client/entry.js" || !imports.has(text)) throw new Error(`${file}:${index + 1}: unsupported import`);
			return imports.get(text);
		}
		if (/^export\b/.test(text)) {
			if (!/^export (const|(?:async )?function)\s+\w+/.test(text)) throw new Error(`${file}:${index + 1}: unsupported export`);
			return line.replace("export ", "");
		}
		return line;
	}).join("\n").trimEnd();
}

// Reflect the pure model's real exports: no second list to forget when adding
// a helper. UI and entry are only read, never imported or executed during build.
const artifact = `/** Generated by node client/build.mjs; edit client/ sources. */
window.__ModuleLoader__.load({
	id: "dsh-openai-api",
	factory: (require) => {
		const existing = document.getElementById("dsh-openai-api-styles");
		const style = existing ?? document.createElement("style");
		style.id = "dsh-openai-api-styles";
		style.textContent = ${JSON.stringify(read("client/styles.css").trimEnd())};
		if (!existing) document.head.appendChild(style);

		const model = (() => {
${inline("client/model.js")}
			return { ${Object.keys(model).join(", ")} };
		})();

${inline("client/ui.js")}

${inline("client/entry.js")}
		return { name, inject, apply };
	},
});
`;

// Catch invalid transforms before replacing the last working bundle.
new Script(artifact, { filename: "lib/client.js" });
if (process.argv.includes("--check")) {
	if (read("lib/client.js") !== artifact) throw new Error("lib/client.js is out of date; run: node client/build.mjs");
	console.log("lib/client.js is up to date");
} else {
	writeFileSync(new URL("lib/client.js", root), artifact);
	console.log("wrote lib/client.js");
}
